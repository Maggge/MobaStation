#!/usr/bin/env python3
"""Compress the web page of the ESP firmware for the build.

Reads the raw string WEB_PAGE of MobaStationESP/WebPage.h and writes WebPageGz.h with the gzip
bytes and an ETag. The firmware serves it with Content-Encoding: gzip, a quarter of the size,
which matters on the slow access point. Without WebPageGz.h (eg. a build in the Arduino IDE)
the firmware serves the plain page.

usage: gzip_page.py WebPage.h OUTPUT_DIR
"""
import gzip
import os
import re
import sys
import zlib

src, out_dir = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8").read()
m = re.search(r'R"=====\((.*?)\)====="', text, re.S)
if not m:
    sys.exit("gzip_page.py: no R\"=====(...)=====\" string in " + src)
page = m.group(1).encode("utf-8")
gz = gzip.compress(page, compresslevel=9, mtime=0)
etag = '"%08x"' % zlib.crc32(page)

lines = ["//generated by extras/esp/gzip_page.py from WebPage.h, do not edit",
         "#pragma once",
         "#include <Arduino.h>",
         "#define WEB_PAGE_ETAG \"\\\"%s\\\"\"" % etag.strip('"'),
         "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {"]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(str(b) for b in gz[i:i + 20]) + ",")
lines.append("};")
data = "\n".join(lines) + "\n"

os.makedirs(out_dir, exist_ok=True)
dst = os.path.join(out_dir, "WebPageGz.h")
#write only on change, so arduino-cli keeps its cache
if not os.path.exists(dst) or open(dst).read() != data:
    open(dst, "w").write(data)
print("web page %d bytes, gzip %d bytes, ETag %s" % (len(page), len(gz), etag))
